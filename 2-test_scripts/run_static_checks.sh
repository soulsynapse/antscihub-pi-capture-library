grep -q 'antcam report focus' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'publish_recording_event' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'recording_start' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'recording_end' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'encrypt=True' "${REPO_ROOT}/1-capture_config/antcam"
! grep -q -- '--no-encrypt' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'write_script_failure_diagnostic' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'diagnostics/recordings' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'resolve_focus_script_path' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'start_focus_check' "${REPO_ROOT}/1-capture_config/antcam"
