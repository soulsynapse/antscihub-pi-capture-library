echo "[static-checks] Checking upload docs for config-path behavior"
grep -q 'config/' "${REPO_ROOT}/4-upload/README.md"
grep -q 'rclone copyto' "${REPO_ROOT}/4-upload/README.md"
grep -q '.MOVED' "${REPO_ROOT}/4-upload/README.md"
