grep -q 'fleet/report/{DEVICE_ID}' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'publish_with_fleet_publish' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'publish_with_mqtt_report_cli' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'encrypt=True' "${REPO_ROOT}/4-upload/upload_worker.sh"
! grep -q -- '--no-encrypt' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'is_config_relative_path' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'rclone copyto' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'size_bytes=' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'message_parts' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'upload_detected' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'upload_renamed' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'upload_retry_scheduled' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'rclone moveto' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q -- '--immutable' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'build_conflict_relative_path' "${REPO_ROOT}/4-upload/upload_worker.sh"
grep -q 'MACHINE_SUFFIX' "${REPO_ROOT}/4-upload/upload_worker.sh"
echo "[static-checks] OK upload worker checks"

echo "[static-checks] Checking install defaults"
grep -q 'Environment="RCLONE_REMOTE=gdrive_personal"' "${REPO_ROOT}/install.sh"
grep -q 'Environment="RCLONE_PATH="' "${REPO_ROOT}/install.sh"
grep -q 'Environment="UPLOAD_DIR=${upload_dir}"' "${REPO_ROOT}/install.sh"
grep -q 'disable_dynamic_camera_service' "${REPO_ROOT}/install.sh"
grep -q 'install_camera_cli' "${REPO_ROOT}/install.sh"
grep -q 'sudo antcam apply imx708' "${REPO_ROOT}/install.sh"
grep -q 'antcam set focus 7.5' "${REPO_ROOT}/install.sh"
grep -q 'antcam report focus' "${REPO_ROOT}/install.sh"
grep -q 'antcam start record_1fps_1m_focus' "${REPO_ROOT}/install.sh"
grep -q 'antcam focus' "${REPO_ROOT}/install.sh"
grep -q 'FOCUS_SCRIPT_SOURCE' "${REPO_ROOT}/install.sh"
grep -q 'FOCUS_SCRIPT_TARGET' "${REPO_ROOT}/install.sh"
grep -q 'RECORDING_SCRIPT_SOURCE_DIR' "${REPO_ROOT}/install.sh"
grep -q 'RECORDING_SCRIPT_TARGET_DIR' "${REPO_ROOT}/install.sh"
grep -q 'MQTT_EVENT_ENABLED' "${REPO_ROOT}/install.sh"
grep -q 'MQTT_REPORT_BIN' "${REPO_ROOT}/install.sh"
grep -q 'FLEET_EVENT_TOPIC_TEMPLATE' "${REPO_ROOT}/install.sh"
