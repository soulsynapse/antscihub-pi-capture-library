grep -q 'focus-result-lens-position-' "${REPO_ROOT}/1-capture_config/antcam"
grep -q '__T-' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'resolve_focus_hostname_for_filename' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'resolve_recording_script_path' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'antcam_focus_autofocus.sh' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'recording-scripts' "${REPO_ROOT}/1-capture_config/antcam"
grep -q 'remove_conflicting_camera_lines' "${REPO_ROOT}/1-capture_config/antcam"
echo "[static-checks] OK antcam checks"

echo "[static-checks] Checking focus helper script"
test -f "${REPO_ROOT}/1-capture_config/antcam_focus_autofocus.sh"
grep -q 'autofocus-mode auto' "${REPO_ROOT}/1-capture_config/antcam_focus_autofocus.sh"
grep -q 'autofocus-on-capture' "${REPO_ROOT}/1-capture_config/antcam_focus_autofocus.sh"
grep -q 'LensPosition=' "${REPO_ROOT}/1-capture_config/antcam_focus_autofocus.sh"
grep -q 'FOCUS_IMAGE_PATH=' "${REPO_ROOT}/1-capture_config/antcam_focus_autofocus.sh"
grep -q 'rpicam-vid --lens-position' "${REPO_ROOT}/1-capture_config/antcam_focus_autofocus.sh"
echo "[static-checks] OK focus helper checks"

echo "[static-checks] Checking recording scripts and docs"
test -f "${REPO_ROOT}/3-recording_scripts/record_1fps_1m_focus.sh"
grep -q 'framerate 1' "${REPO_ROOT}/3-recording_scripts/record_1fps_1m_focus.sh"
grep -q 'segment 60000' "${REPO_ROOT}/3-recording_scripts/record_1fps_1m_focus.sh"
grep -q 'lens-position' "${REPO_ROOT}/3-recording_scripts/record_1fps_1m_focus.sh"
grep -q 'ANTCAM_FOCUS_VALUE_FILE' "${REPO_ROOT}/3-recording_scripts/record_1fps_1m_focus.sh"
test -f "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'recording_start' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'recording_end' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'diagnostics/recordings' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'antcam start <recording-script-name>' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'antcam focus' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'antcam_focus_autofocus.sh' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'lens-position' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q 'focus-result-lens-position-' "${REPO_ROOT}/3-recording_scripts/README.md"
grep -q '__T-HH-MM-SS__' "${REPO_ROOT}/3-recording_scripts/README.md"
